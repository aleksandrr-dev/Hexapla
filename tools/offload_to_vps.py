def expand(parent, entries):
    out = []
    excl = tuple(e[1:] for e in entries if e.startswith("!"))
    for e in entries:
        if e.startswith("!"):
            continue
        if e == "*":
            out += sorted(n for n in os.listdir(parent) if not n.startswith(excl))
        elif e.endswith("*"):
            out += sorted(n for n in os.listdir(parent) if n.startswith(e[:-1]))
        elif os.path.exists(os.path.join(parent, e)):
            out.append(e)
    return out


def walk_stats(parent, names):
    """(file count, bytes, newest mtime). Raises on an unreadable tree -- never a plausible 0."""
    count = size = 0
    newest = 0.0
    for n in names:
        p = os.path.join(parent, n)
        if os.path.isfile(p):
            st = os.stat(p)
            count, size, newest = count + 1, size + st.st_size, max(newest, st.st_mtime)
            continue
        def onerr(err):
            raise err
        for root, _, files in os.walk(p, onerror=onerr):
            for f in files:
                st = os.stat(os.path.join(root, f))
                count, size, newest = count + 1, size + st.st_size, max(newest, st.st_mtime)
    return count, size, newest


def process_cmdlines():
    ps = ("Get-CimInstance Win32_Process | Where-Object { $_.CommandLine } | "
          "ForEach-Object { $_.CommandLine } | ConvertTo-Json -Compress")
    r = subprocess.run(["powershell", "-NoProfile", "-Command", ps],
                       capture_output=True, text=True, encoding="utf-8", errors="replace")
    if r.returncode != 0 or not r.stdout.strip():
        raise RuntimeError("process listing failed: " + r.stderr.strip()[:300])
    data = json.loads(r.stdout)
    return [data] if isinstance(data, str) else data


def users_of(parent, names, cmdlines):
    hits = []
    for n in names:
        needle = os.path.join(parent, n).lower()
        alt = needle.replace("\\", "/")
        for c in cmdlines:
            lc = c.lower()
            if (needle in lc or alt in lc) and "offload_to_vps.py" not in lc:
                hits.append(c[:150])
    return hits


def ssh(cmd, **kw):
    return subprocess.run(["ssh", "-o", "BatchMode=yes", HOST, cmd],
                          capture_output=True, text=True, **kw)


def human(n):
    for u in ("B", "KB", "MB", "GB"):
        if n < 1024:
            return "%.1f %s" % (n, u)
        n /= 1024
    return "%.1f TB" % n


def upload(name, parent, names):
    """Stream tar -> ssh, hashing on the way. Returns local sha256."""
    remote = "%s/%s.tar" % (REMOTE_DIR, name)
    tar = subprocess.Popen([r"C:\Windows\System32\tar.exe", "-cf", "-", "-C", parent] + names,
                           stdout=subprocess.PIPE)
    sink = subprocess.Popen(["ssh", "-o", "BatchMode=yes", HOST, "cat > '%s.part'" % remote],
                            stdin=subprocess.PIPE)
    h, sent, t0 = hashlib.sha256(), 0, time.time()
    while True:
        buf = tar.stdout.read(4 << 20)
        if not buf:
            break
        h.update(buf)
        sink.stdin.write(buf)
        sent += len(buf)
        if sent % (512 << 20) < (4 << 20):
            print("    ... %s sent (%.0f MB/s)" % (human(sent), sent / 1e6 / max(1, time.time() - t0)),
                  flush=True)
    sink.stdin.close()
    rc_tar, rc_ssh = tar.wait(), sink.wait()
    if rc_tar != 0 or rc_ssh != 0:
        raise RuntimeError("upload failed: tar rc=%d ssh rc=%d" % (rc_tar, rc_ssh))
    r = ssh("mv '%s.part' '%s'" % (remote, remote))
    if r.returncode != 0:
        raise RuntimeError("remote rename failed: " + r.stderr)
    return h.hexdigest(), sent


def verify(name, local_sha, local_count):
    remote = "%s/%s.tar" % (REMOTE_DIR, name)
    r = ssh("sha256sum '%s' | cut -d' ' -f1; tar -tf '%s' | grep -vc '/$'" % (remote, remote))
    lines = r.stdout.split()
    if r.returncode != 0 or len(lines) != 2:
        raise RuntimeError("remote verify could not run: rc=%d %s" % (r.returncode, r.stderr[:200]))
    rsha, rcount = lines[0], int(lines[1])
    ok = rsha == local_sha and rcount == local_count
    print("    verify: sha %s, files local %d / remote %d -> %s"
          % ("match" if rsha == local_sha else "MISMATCH", local_count, rcount, "OK" if ok else "FAIL"))
    return ok


def remove_local(parent, names):
    for n in names:
        p = os.path.join(parent, n)
        if os.path.isdir(p):
            shutil.rmtree(p)
        else:
            os.remove(p)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true", help="really upload and remove (default: dry run)")
    ap.add_argument("--only", nargs="*", help="item names to process")
    a = ap.parse_args()

    items = [i for i in ITEMS if not a.only or i[0] in a.only]
    cmdlines = process_cmdlines()
    now = time.time()
    plan, total, blocked = [], 0, 0
    print("%s  ->  %s:%s\n" % ("APPLY" if a.apply else "DRY RUN (nothing changes)", HOST, REMOTE_DIR))
    for name, kind, parent, entries in items:
        names = expand(parent, entries)
        if not names:
            print("[%s] nothing found under %s -- skipped\n" % (name, parent))
            continue
        ok_names, skipped = [], []
        for n in names:
            _, _, nn = walk_stats(parent, [n])
            u = users_of(parent, [n], cmdlines)
            if u:
                skipped.append((n, "IN USE by: " + u[0]))
            elif now - nn < FRESH_SECONDS:
                skipped.append((n, "modified %s (< 24 h)" % time.strftime("%m-%d %H:%M", time.localtime(nn))))
            else:
                ok_names.append(n)
        for n, why in skipped:
            print("[%s] SKIP %s -- %s" % (name, os.path.join(parent, n), why))
        blocked += len(skipped)
        if not ok_names:
            print()
            continue
        count, size, newest = walk_stats(parent, ok_names)
        print("[%s] %s  %s  %d files in %d entries  newest %s"
              % (name, kind, human(size), count, len(ok_names),
                 time.strftime("%Y-%m-%d %H:%M", time.localtime(newest))))
        for n in ok_names[:6]:
            print("    " + os.path.join(parent, n))
        if len(ok_names) > 6:
            print("    ... +%d more" % (len(ok_names) - 6))
        print()
        plan.append((name, kind, parent, ok_names, count, size))
        total += size

    r = ssh("df -B1 --output=avail %s | tail -1" % os.path.dirname(REMOTE_DIR))
    try:
        remote_free = int(r.stdout.strip())
    except ValueError:
        print("cannot read VPS free space: %s %s" % (r.stdout, r.stderr))
        return 2
    upload_bytes = sum(p[5] for p in plan if p[1] == "offload")
    print("Frees locally: %s   uploads: %s   VPS free: %s   skipped entries: %d"
          % (human(total), human(upload_bytes), human(remote_free), blocked))
    if upload_bytes > remote_free * 0.9:
        print("VPS lacks room -- stopping.")
        return 2
    if not a.apply:
        print("\nDry run only. Re-run with --apply to do it.")
        return 0

    r = ssh("sudo -n mkdir -p %s && sudo -n chown ubuntu:ubuntu %s" % (REMOTE_DIR, REMOTE_DIR))
    if r.returncode != 0:
        print("cannot create %s on VPS: %s" % (REMOTE_DIR, r.stderr))
        return 2
    failed = 0
    for name, kind, parent, names, count, size in plan:
        print("[%s]" % name)
        if kind == "offload":
            sha, sent = upload(name, parent, names)
            print("    sent %s, sha256 %s" % (human(sent), sha[:16]))
            if not verify(name, sha, count):
                print("    local copy KEPT")
                failed += 1
                continue
        if users_of(parent, names, process_cmdlines()):
            print("    became in use -- local copy KEPT")
            failed += 1
            continue
        remove_local(parent, names)
        gone = not any(os.path.exists(os.path.join(parent, n)) for n in names)
        print("    local removed: %s" % ("yes" if gone else "NO (some paths remain)"))
        failed += 0 if gone else 1
    print("\n%d item(s) failed" % failed if failed else "\nall items done")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
