/** Plans.distribute: a flat chapter list spread evenly, ceil per day. */
export function distribute(chapters: Chap[], totalDays: number): PlanDay[] {
  const days = Math.max(1, Math.min(totalDays, chapters.length));
  const out: PlanDay[] = [];
  let index = 0;
  for (let day = 0; day < days; day += 1) {
    const take = Math.ceil((chapters.length - index) / (days - day));
    out.push({ day: day + 1, chapters: chapters.slice(index, index + take) });
    index += take;
  }
  return out;
}

/** ChronoOrder.chapters(): every canon chapter once. Throws on a repeat or a
 *  count other than 1189 — a broken order must not quietly become a plan. */
export function chronoChapters(order: string = CHRONO_ORDER): Chap[] {
  const out: Chap[] = [];
  const seen = new Set<string>();
  for (const token of order.split(" ")) {
    const [book, range] = token.split(":");
    const b = Number(book);
    const [first, last = first] = range.split("-").map(Number);
    for (let ch = first; ch <= last; ch += 1) {
      const k = String(b) + ":" + String(ch - 1);
      if (seen.has(k)) throw new Error("CHRONO_ORDER repeats chapter " + k);
      seen.add(k);
      out.push([b, ch - 1]);
    }
  }
  if (out.length !== 1189) throw new Error("CHRONO_ORDER expands to " + String(out.length) + " chapters, expected 1189");
  return out;
}

export function eraByDay(days: PlanDay[]): Map<number, string> {
  const m = new Map<number, string>();
  for (const [b, c, key] of ERAS) {
    const d = days.find((x) => x.chapters.some((y) => y[0] === b && y[1] === c));
    if (d !== undefined && !m.has(d.day)) m.set(d.day, key);
  }
  return m;
}

let cached: Plan[] | null = null;

/** The six plans, in the Android tab order. */
export function buildPlans(): Plan[] {
  if (cached !== null) return cached;
  const all: Chap[] = [];
  KJV_CHAPTERS.forEach((n, b) => {
    for (let c = 0; c < n; c += 1) all.push([b, c]);
  });
  const chrono = distribute(chronoChapters(), 365);
  const plan = (id: string, title: string, desc: string, days: PlanDay[], eras = new Map<number, string>()): Plan => ({ id, title, desc, days, eraByDay: eras });
  cached = [
    plan("year", "plan_year", "plan_year_desc", distribute(all, 365)),
    plan("chrono", "plan_chrono", "plan_chrono_desc", chrono, eraByDay(chrono)),
    plan("nt90", "plan_nt90", "plan_nt90_desc", distribute(all.filter((x) => x[0] >= 39), 90)),
    plan("gospels30", "plan_gospels", "plan_gospels_desc", distribute(all.filter((x) => x[0] >= 39 && x[0] <= 42), 30)),
    plan("prov31", "plan_proverbs", "plan_proverbs_desc", distribute(all.filter((x) => x[0] === 19), 31)),
    plan("ps75", "plan_psalms", "plan_psalms_desc", distribute(all.filter((x) => x[0] === 18), 75)),
  ];
  return cached;
}

/** The first day not done, or the last day when every day is (PlansScreen). */
export function nextDay(plan: Plan, done: Set<number>): number {
  return plan.days.find((d) => !done.has(d.day))?.day ?? plan.days.length;
}

// ---- Progress, kept in this browser only (web/README.md house rule 4) ----

export interface PlanState {
  /** The plan last open, as Store.lastPlanId. */
  last: string;
  /** Plan id -> the day numbers ticked. */
  done: Record<string, number[]>;
  /** The daily reading streak, as Store.bumpStreak: days in a row the app was
   *  opened, and the local day (YYYY-MM-DD) it last counted. */
  streak: number;
  streakDay: string;
}

export const EMPTY_PLANS: PlanState = { last: "", done: {}, streak: 0, streakDay: "" };

/** Stored JSON -> PlanState; anything malformed is dropped, never thrown. */
export function cleanPlanState(x: unknown): PlanState {
  if (x === null || typeof x !== "object") return { ...EMPTY_PLANS, done: {} };
  const p = x as Record<string, unknown>;
  const done: Record<string, number[]> = {};
  if (p.done !== null && typeof p.done === "object") {
    for (const [id, days] of Object.entries(p.done as Record<string, unknown>)) {
      if (!Array.isArray(days)) continue;
      const ok = [...new Set(days.filter((d): d is number => Number.isInteger(d) && d >= 1 && d <= 365))].sort((a, b) => a - b);
      if (ok.length > 0) done[id] = ok;
    }
  }
  return {
    last: typeof p.last === "string" ? p.last : "",
    done,
    streak: Number.isInteger(p.streak) && (p.streak as number) >= 0 ? (p.streak as number) : 0,
    streakDay: typeof p.streakDay === "string" && /^\d{4}-\d{2}-\d{2}$/.test(p.streakDay) ? p.streakDay : "",
  };
}

export function toggled(s: PlanState, id: string, day: number): PlanState {
  const cur = new Set(s.done[id] ?? []);
  if (cur.has(day)) cur.delete(day);
  else cur.add(day);
  const done = { ...s.done };
  if (cur.size === 0) delete done[id];
  else done[id] = [...cur].sort((a, b) => a - b);
  return { ...s, done };
}

export function reset(s: PlanState, id: string): PlanState {
  const done = { ...s.done };
  delete done[id];
  return { ...s, done };
}

/** A local calendar day as YYYY-MM-DD. */
export function dayOf(d: Date): string {
  const p = (n: number) => String(n).padStart(2, "0");
  return String(d.getFullYear()) + "-" + p(d.getMonth() + 1) + "-" + p(d.getDate());
}

/** Store.touchStreak: same day keeps it (at least 1), the next day adds one,
 *  a gap restarts at 1. Called once per app open. */
export function bumped(s: PlanState, now: Date): PlanState {
  const today = dayOf(now);
  if (s.streakDay === today) return s.streak >= 1 ? s : { ...s, streak: 1 };
  const y = new Date(now.getFullYear(), now.getMonth(), now.getDate() - 1);
  return { ...s, streak: s.streakDay === dayOf(y) ? s.streak + 1 : 1, streakDay: today };
}

const KEY = "hexapla.plans.v1";

export function loadPlanState(): PlanState {
  try {
    const raw = window.localStorage.getItem(KEY);
    return raw === null ? { ...EMPTY_PLANS, done: {} } : cleanPlanState(JSON.parse(raw));
  } catch {
    return { ...EMPTY_PLANS, done: {} };
  }
}

export function savePlanState(s: PlanState): void {
  try {
    window.localStorage.setItem(KEY, JSON.stringify(s));
  } catch {
    // Storage unavailable: ticks last until the page closes.
  }
}
