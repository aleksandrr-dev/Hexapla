/** A chapter on the KJV grid: [book, chapter], both 0-based. */
export type Chap = [number, number];

export interface PlanDay {
  /** 1-based, as progress stores it. */
  day: number;
  chapters: Chap[];
}

export interface Plan {
  id: string;
  /** i18n keys, the Android string names. */
  title: string;
  desc: string;
  days: PlanDay[];
  /** Day -> era heading key, on the day holding the era's first chapter. */
  eraByDay: Map<number, string>;
}

